WITH DateRange AS (
    SELECT @DT1 AS DateValue
    UNION ALL
    SELECT DATEADD(DAY, 1, DateValue)
    FROM DateRange
    WHERE DateValue < @DT2
)

SELECT  @COLS = STRING_AGG(QUOTENAME(Dates + '_' + Metric), ',')
FROM (
    SELECT CONVERT(char(10), DateValue, 120) AS Dates, B.Metric
	FROM DateRange A
	CROSS JOIN (
				SELECT 'STK_Q' AS Metric UNION ALL
				SELECT 'STK_V' AS Metric UNION ALL
				SELECT 'SALE_Q' AS Metric UNION ALL
				SELECT 'SALE_V' AS Metric UNION ALL
				SELECT 'GM' AS Metric
	)B

) AS PivotCols;

-- Build the dynamic SQL for pivoting and inserting into the new table
SET @SQL = '
WITH CTE_PIVOT AS (
    SELECT
	MATNR,
        A.STORE_CODE,
        CONVERT(VARCHAR(10), A.DATES, 120) + ''_'' + A.PARTICULARS_NAME AS PivotCol,
        SUM(A.PARTICULARS_VALUE) AS Value
    FROM TREND_KPI_DATA (NOLOCK) A
    GROUP BY MATNR,A.STORE_CODE,CONVERT(VARCHAR(10), A.DATES, 120) + ''_'' + A.PARTICULARS_NAME
)
SELECT
    MATNR,
    STORE_CODE,
    ' + @COLS + '
INTO PROCESS_DATA_SALE_STK_L30_DAYS
FROM CTE_PIVOT
PIVOT (
    SUM(Value) FOR PivotCol IN (' + @COLS + ')
) AS P;
';

-- Execute the dynamic SQL
EXEC sp_executesql @SQL;


 --CREATE A CLUSTERED INDEX FOR PERFORMANCE
	CREATE CLUSTERED INDEX IDX_PROCESS_DATA_SALE_STK_L30_DAYS_STORE_MATNR
	ON PROCESS_DATA_SALE_STK_L30_DAYS (STORE_CODE, MATNR);

