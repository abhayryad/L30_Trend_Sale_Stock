ALTER    PROCEDURE [dbo].[USP_MRST_SAL_STK_L30_TREND]
@CAT_COLUMNS AS VARCHAR(MAX)='',
@CAT_COLUMNS_ALIAS AS VARCHAR(MAX)='',
@STORE_CODES AS VARCHAR(MAX)=''
AS
BEGIN

	DECLARE @CONDITION VARCHAR(100) = '';

	IF @CAT_COLUMNS_ALIAS LIKE '%VAR-ART%'
	BEGIN
	SET @CONDITION = 'AND LEN(B.ARTICLE_NUMBER) =13';
	END

	ELSE IF @CAT_COLUMNS_ALIAS = 'MERGE_VENDOR_CODE AS [M-VND-CD]'
	BEGIN
		SET @CONDITION  = 'AND B.SEG IN (''APP'',''GM'',''MKT'')'
	END

	--select @CONDITION

	IF NOT OBJECT_ID('tempdb..#tmp_COLUMS') IS NULL DROP TABLE #tmp_COLUMS;

	WITH OrderedColumns AS (
    SELECT
        COLUMN_NAME,
        ROW_NUMBER() OVER (ORDER BY CAST(SUBSTRING(COLUMN_NAME, 1, 10) AS DATE)) AS ROWID
    FROM INFORMATION_SCHEMA.COLUMNS
    WHERE TABLE_NAME = 'PROCESS_DATA_SALE_STK_L30_DAYS'
      AND COLUMN_NAME NOT IN ('MATNR', 'STORE_CODE')
	)
	SELECT * INTO  #tmp_COLUMS   FROM OrderedColumns;

	DECLARE @SQL NVARCHAR(MAX)='';
	DECLARE @ROW INT =1;
	DECLARE @MaxROW INT
	SELECT @MaxROW = (select max(ROWID) from #tmp_COLUMS);
	DECLARE @COL NVARCHAR(MAX)='';
	DECLARE @COLUMNS NVARCHAR(MAX)='';
	DECLARE @COLUMNS_NULL NVARCHAR(MAX)='';
	DECLARE @COLUMNS_SUM NVARCHAR(MAX)='';



	WHILE @ROW <= @MaxROW
	BEGIN
			SELECT @COL = COLUMN_NAME FROM #tmp_COLUMS WHERE ROWID = @ROW;

			SET @COLUMNS = @COLUMNS + '[' + @COL + '],'

			IF @COL NOT IN (
				'CM_BGT_SALE_V', 'CM+1_BGT_SALE_V', 'CM+2_BGT_SALE_V',
				'CM_BGT_DISP_V', 'CM+1_BGT_DISP_V',
				'CM_BGT_SALE_Q', 'CM+1_BGT_SALE_Q', 'CM+2_BGT_SALE_Q',
				'CM_BGT_DISP_Q', 'CM+1_BGT_DISP_Q'
			)
			BEGIN
				SET @COLUMNS_NULL = @COLUMNS_NULL + 'ISNULL([' + @COL + '], 0.0) [' + @COL + '],'
				SET @COLUMNS_SUM  = @COLUMNS_SUM  + 'ISNULL(SUM([' + @COL + ']),0.0) AS [' + @COL + '],'
			END

			SET @ROW = @ROW + 1
	END

	SET @COLUMNS = LEFT(@COLUMNS, LEN(@COLUMNS) - 1)
	SET @COLUMNS_NULL = LEFT(@COLUMNS_NULL, LEN(@COLUMNS_NULL) - 1)
	SET @COLUMNS_SUM = LEFT(@COLUMNS_SUM, LEN(@COLUMNS_SUM) - 1)


	IF NOT OBJECT_ID('tempdb..#tmp') IS NULL DROP TABLE #tmp;
	SELECT * INTO #tmp from dbo.Split(@CAT_COLUMNS,',');


	SET @ROW=1;
	SET @MaxROW=(select max(Id) from #tmp);
	SET @COL=''
	DECLARE @HIERARCHY_COLS VARCHAR(MAX)='';

	WHILE @ROW<=@MaxROW
	BEGIN
		SELECT @COL=Data FROM #tmp WHERE ID=@ROW;
		BEGIN
			SET @HIERARCHY_COLS=@HIERARCHY_COLS+'['+@COL+'],'
		END

		SET @ROW=@ROW+1
	END

	SET @HIERARCHY_COLS=LEFT(@HIERARCHY_COLS,LEN(@HIERARCHY_COLS)-1)

	--select @HIERARCHY_COLS as hierachy_col


	DECLARE @FILTER_PARAM NVARCHAR(MAX)='';

	IF @STORE_CODES<>''
	BEGIN
	SELECT A.STORE_CODE INTO #TMP_STORE FROM
			(SELECT [Data] STORE_CODE from dbo.Split(@STORE_CODES,',')) AS A
			INNER JOIN [dbo].[STORE_PLANT_MASTER](nolock) B ON A.STORE_CODE=B.ST_CD
		SET @FILTER_PARAM=' WHERE STORE_CODE IN (SELECT STORE_CODE FROM #TMP_STORE)'
	END
	ELSE
	BEGIN
		SET @FILTER_PARAM = 'WHERE 1 = 1 '
		--SET @FILTER_PARAM=' WHERE STORE_CODE IN (
		--	SELECT ST_CD FROM STORE_PLANT_MASTER(NOLOCK) WHERE [ST_STAT]=''ACT'' AND ST_TYP IN (''STORE'') GROUP BY ST_CD) '
	END

	--select @FILTER_PARAM, @COLUMNS_SUM as col_sum


	SET @SQL=
	'
	    SELECT  '+@CAT_COLUMNS_ALIAS+', '+@COLUMNS_SUM+'
				FROM PROCESS_DATA_SALE_STK_L30_DAYS (NOLOCK) A
				INNER JOIN DIM_PRODUCT(NOLOCK) B ON  A.MATNR  = B.ARTICLE_NUMBER
				INNER JOIN STORE_PLANT_MASTER C ON A.STORE_CODE =C.ST_CD AND [ST_STAT]=''ACT'' AND ST_TYP = ''STORE''
				'+@FILTER_PARAM+'
				'+@CONDITION+'
				GROUP BY '+@HIERARCHY_COLS+'
	'

	--print (@sql)

	EXEC sp_executesql @SQL;

	--LEFT JOIN CTE_PRODUCT B ON CAST(A.MATNR AS BIGINT)= CAST(B.MATNR AS BIGINT)
	--LEFT JOIN CTE_SUP C ON CAST(B.EXTWG AS BIGINT) = CAST(C.LIFNR AS BIGINT)
	--LEFT JOIN vw_ET_ART_Broader_Menu_DATA (NOLOCK) D ON LEFT(CAST(A.MATNR AS BIGINT),10) = CAST(D.MATNR AS BIGINT)

END
