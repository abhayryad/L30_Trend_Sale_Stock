*/
ALTER PROCEDURE [dbo].[USP_GENERATE_L30D_STK_SALE_VQ_MRST]
AS
BEGIN

	TRUNCATE TABLE TREND_KPI_DATA

	DROP INDEX IX_TREND_KPI_DATA_MATNR_WERKS_Date ON TREND_KPI_DATA;


	DECLARE @CURR_DATE DATE = DATEADD(DAY,-1,GETDATE());
	DECLARE @DT2 DATE = @CURR_DATE, @DT1 DATE= DATEADD(DAY,-30,@CURR_DATE)

	;WITH CTE_RAW AS(
		SELECT TRY_CAST(MATNR AS BIGINT) MATNR,WERKS,CONVERT(char(10), stock_Date, 120) AS stock_Date,SUM(LABST_DMBTR) STK_V,SUM(LABST) AS STK_Q  FROM ET_STOCK_DATA_LOG(NOLOCK)
			WHERE stock_Date BETWEEN @DT1 AND @DT2 AND LGORT IN ('0001','0006')
			--AND WERKS  = 'HB05'
				GROUP BY TRY_CAST(MATNR AS BIGINT),WERKS,CONVERT(char(10), stock_Date, 120)
				UNION
		SELECT TRY_CAST(MATNR AS BIGINT) MATNR,WERKS,CONVERT(char(10), stock_Date, 120) AS stock_Date,SUM(LABST_DMBTR) STK_V,SUM(LABST) AS STK_Q  FROM ET_STOCK_DATA(NOLOCK)
			WHERE stock_Date=@DT2 AND LGORT IN ('0001','0006')
			--AND WERKS  = 'HB05'
				GROUP BY TRY_CAST(MATNR AS BIGINT),WERKS,CONVERT(char(10), stock_Date, 120)
	),
	CTE_STK_UNPIV AS (
    SELECT MATNR, WERKS, stock_Date, Metric, Value
    FROM CTE_RAW
    UNPIVOT (
        Value FOR Metric IN ([STK_V], [STK_Q])
    ) AS U
)
	INSERT INTO TREND_KPI_DATA (MATNR, STORE_CODE, DATES, PARTICULARS_NAME, PARTICULARS_VALUE)
	SELECT MATNR, WERKS, stock_Date, Metric, Value FROM CTE_STK_UNPIV;



	;WITH CTE_SALE AS
	(
	SELECT TRY_CAST(ARTICLE_NUMBER AS BIGINT) MATNR,STORE_CODE WERKS,CONVERT(char(10), Sales_Date, 120) AS SALES_DATE,SUM(SALE_VAL) SALE_V,SUM(SALE_QTY) SALE_Q,SUM(SALE_VAL-NET_MAP) GM FROM VIEW_ET_SALES_DATA(NOLOCK)
		WHERE Sales_Date BETWEEN @DT1 AND @DT2
		GROUP BY TRY_CAST(ARTICLE_NUMBER AS BIGINT),STORE_CODE,CONVERT(char(10), Sales_Date, 120)
	),
	CTE_SALE_UNPIV AS (
    SELECT MATNR, WERKS, SALES_DATE, Metric, Value
    FROM CTE_SALE
    UNPIVOT (
        Value FOR Metric IN ([SALE_V], [SALE_Q],[GM])
    ) AS U
)
	INSERT INTO TREND_KPI_DATA (MATNR, STORE_CODE, DATES, PARTICULARS_NAME, PARTICULARS_VALUE)
	SELECT MATNR, WERKS, SALES_DATE, Metric, Value FROM CTE_SALE_UNPIV;

    CREATE CLUSTERED INDEX IX_TREND_KPI_DATA_MATNR_WERKS_Date ON TREND_KPI_DATA (MATNR, STORE_CODE, DATES);

END
