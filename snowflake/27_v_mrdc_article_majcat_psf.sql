-- V_MRDC_ARTICLE_MAJCAT_PSF: all-stores article (MATNR) PSF summary, with the all-stores MAJ-CAT PSF/STR averages
-- brought alongside, matched on MAJ-CAT only (MAJ-CAT is unique in the MAJ-CAT summary, so no row fan-out).
--   All columns of V_MRDC_TREND_30_DAYS_GRID_PSF_SUMMARY, then MAJCAT_<KPI>_<window> from
--   V_MRDC_TREND_MAJ_CAT_30_DAYS_GRID_PSF_SUMMARY for KPI = SALE_PSF, GP_PSF, STR and window = MTD, L7D, 30D, TD.
--   Articles with no matching MAJ-CAT row get 0.
-- Run 26_v_mrdc_psf_summary.sql first.

CREATE OR REPLACE VIEW V2RETAIL.SILVER.V_MRDC_ARTICLE_MAJCAT_PSF AS
SELECT A.*,
       COALESCE(M.SALE_PSF_MTD, 0) AS MAJCAT_SALE_PSF_MTD,
       COALESCE(M.SALE_PSF_L7D, 0) AS MAJCAT_SALE_PSF_L7D,
       COALESCE(M.SALE_PSF_30D, 0) AS MAJCAT_SALE_PSF_30D,
       COALESCE(M.SALE_PSF_TD, 0)  AS MAJCAT_SALE_PSF_TD,
       COALESCE(M.GP_PSF_MTD, 0)   AS MAJCAT_GP_PSF_MTD,
       COALESCE(M.GP_PSF_L7D, 0)   AS MAJCAT_GP_PSF_L7D,
       COALESCE(M.GP_PSF_30D, 0)   AS MAJCAT_GP_PSF_30D,
       COALESCE(M.GP_PSF_TD, 0)    AS MAJCAT_GP_PSF_TD,
       COALESCE(M.STR_MTD, 0)      AS MAJCAT_STR_MTD,
       COALESCE(M.STR_L7D, 0)      AS MAJCAT_STR_L7D,
       COALESCE(M.STR_30D, 0)      AS MAJCAT_STR_30D,
       COALESCE(M.STR_TD, 0)       AS MAJCAT_STR_TD
FROM V2RETAIL.SILVER.V_MRDC_TREND_30_DAYS_GRID_PSF_SUMMARY A
LEFT JOIN V2RETAIL.SILVER.V_MRDC_TREND_MAJ_CAT_30_DAYS_GRID_PSF_SUMMARY M
       ON A."MAJ-CAT" = M."MAJ-CAT";
