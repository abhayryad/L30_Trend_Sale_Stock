-- V_ARTICLE_MAJCAT_PSF_ACH: V_ARTICLE_MAJCAT_PSF + article-vs-store/MAJ-CAT PSF achievement.
--   ST_MAJ_CAT_<window>_SALE_ACHIEVEMENT = article SALE_PSF_<window> / MAJCAT_SALE_PSF_<window>
--   ST_MAJ_CAT_<window>_GP_ACHIEVEMENT   = article GP_PSF_<window>   / MAJCAT_GP_PSF_<window>
--   for window = TD, MTD, L7D, 30D. A ratio (1 = on par with the store + MAJ-CAT average).
--   Divide-by-zero comes out as 0.
-- Run 21_v_article_majcat_psf.sql first.

CREATE OR REPLACE VIEW V2RETAIL.SILVER.V_ARTICLE_MAJCAT_PSF_ACH AS
SELECT A.*,
       COALESCE(DIV0NULL(SALE_PSF_TD,  MAJCAT_SALE_PSF_TD),  0) AS ST_MAJ_CAT_TD_SALE_ACHIEVEMENT,
       COALESCE(DIV0NULL(SALE_PSF_MTD, MAJCAT_SALE_PSF_MTD), 0) AS ST_MAJ_CAT_MTD_SALE_ACHIEVEMENT,
       COALESCE(DIV0NULL(SALE_PSF_L7D, MAJCAT_SALE_PSF_L7D), 0) AS ST_MAJ_CAT_L7D_SALE_ACHIEVEMENT,
       COALESCE(DIV0NULL(SALE_PSF_30D, MAJCAT_SALE_PSF_30D), 0) AS ST_MAJ_CAT_30D_SALE_ACHIEVEMENT,
       COALESCE(DIV0NULL(GP_PSF_TD,    MAJCAT_GP_PSF_TD),    0) AS ST_MAJ_CAT_TD_GP_ACHIEVEMENT,
       COALESCE(DIV0NULL(GP_PSF_MTD,   MAJCAT_GP_PSF_MTD),   0) AS ST_MAJ_CAT_MTD_GP_ACHIEVEMENT,
       COALESCE(DIV0NULL(GP_PSF_L7D,   MAJCAT_GP_PSF_L7D),   0) AS ST_MAJ_CAT_L7D_GP_ACHIEVEMENT,
       COALESCE(DIV0NULL(GP_PSF_30D,   MAJCAT_GP_PSF_30D),   0) AS ST_MAJ_CAT_30D_GP_ACHIEVEMENT
FROM V2RETAIL.SILVER.V_ARTICLE_MAJCAT_PSF A;
