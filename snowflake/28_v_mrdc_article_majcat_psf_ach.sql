-- V_MRDC_ARTICLE_MAJCAT_PSF_ACH: V_MRDC_ARTICLE_MAJCAT_PSF + article-vs-MAJ-CAT PSF achievement (all stores).
--   MAJ_CAT_<window>_SALE_ACHIEVEMENT = article SALE_PSF_<window> / MAJCAT_SALE_PSF_<window> * 100
--   MAJ_CAT_<window>_GP_ACHIEVEMENT   = article GP_PSF_<window>   / MAJCAT_GP_PSF_<window> * 100
--   for window = TD, MTD, L7D, 30D. Shown as a whole-number percent string, e.g. '125%' (100% = on par with the MAJ-CAT average).
--   Divide-by-zero comes out as '0%'.
--   Same formulas as V_ARTICLE_MAJCAT_PSF_ACH; the prefix is MAJ_CAT_ rather than ST_MAJ_CAT_ because there is no store.
-- Run 27_v_mrdc_article_majcat_psf.sql first.

CREATE OR REPLACE VIEW V2RETAIL.SILVER.V_MRDC_ARTICLE_MAJCAT_PSF_ACH AS
SELECT A.*,
       TO_VARCHAR(ROUND(COALESCE(DIV0NULL(SALE_PSF_TD,  MAJCAT_SALE_PSF_TD),  0) * 100, 0)::INT) || '%' AS MAJ_CAT_TD_SALE_ACHIEVEMENT,
       TO_VARCHAR(ROUND(COALESCE(DIV0NULL(SALE_PSF_MTD, MAJCAT_SALE_PSF_MTD), 0) * 100, 0)::INT) || '%' AS MAJ_CAT_MTD_SALE_ACHIEVEMENT,
       TO_VARCHAR(ROUND(COALESCE(DIV0NULL(SALE_PSF_L7D, MAJCAT_SALE_PSF_L7D), 0) * 100, 0)::INT) || '%' AS MAJ_CAT_L7D_SALE_ACHIEVEMENT,
       TO_VARCHAR(ROUND(COALESCE(DIV0NULL(SALE_PSF_30D, MAJCAT_SALE_PSF_30D), 0) * 100, 0)::INT) || '%' AS MAJ_CAT_30D_SALE_ACHIEVEMENT,
       TO_VARCHAR(ROUND(COALESCE(DIV0NULL(GP_PSF_TD,    MAJCAT_GP_PSF_TD),    0) * 100, 0)::INT) || '%' AS MAJ_CAT_TD_GP_ACHIEVEMENT,
       TO_VARCHAR(ROUND(COALESCE(DIV0NULL(GP_PSF_MTD,   MAJCAT_GP_PSF_MTD),   0) * 100, 0)::INT) || '%' AS MAJ_CAT_MTD_GP_ACHIEVEMENT,
       TO_VARCHAR(ROUND(COALESCE(DIV0NULL(GP_PSF_L7D,   MAJCAT_GP_PSF_L7D),   0) * 100, 0)::INT) || '%' AS MAJ_CAT_L7D_GP_ACHIEVEMENT,
       TO_VARCHAR(ROUND(COALESCE(DIV0NULL(GP_PSF_30D,   MAJCAT_GP_PSF_30D),   0) * 100, 0)::INT) || '%' AS MAJ_CAT_30D_GP_ACHIEVEMENT
FROM V2RETAIL.SILVER.V_MRDC_ARTICLE_MAJCAT_PSF A;
