-- its task. Replaced by the tables of 32_trend_grid_tables.sql:
--   MRST_ST_MAJ_CAT_TREND, MRST_ST_ART_TREND (store chain), MRDC_MAJ_CAT_TREND, MRDC_ART_TREND (MRDC chain).
--
-- Checked before writing this:
--   * New tables vs old views (2026-10-17, first build): 0 differences in ARTICLE_HV, averages, MAJCAT
--     benchmark, achievement, PPA (14,784,593 / 550,968 / 180,361 / 794 rows).
--   * Readers in the last 30 days (ACCOUNT_USAGE.QUERY_HISTORY): ABHAY_YADAV (ad hoc + comparisons),
--     the TREND_L30_PSF_VIEWS task, SHUBHAM_SVC (ad hoc: get_ddl, temp copies, 2026-10-16),
--     UNIVERSAL_MCP_SVC (one ad-hoc look, 2026-10-17). No scheduled reader outside this pipeline.
--   * GOLD.SP_REFRESH_MIS_NAV_TREND30 (MIS_NAV_TREND30) reads TREND_KPI_DATA directly, not these views.
--   * OBJECT_DEPENDENCIES / procedures / task versions: nothing else references the 18 views.
--
-- Views can't be UNDROPped. To bring them back: re-run 30_USP_REBUILD_PSF_VIEWS.sql (base + PSF views)
-- and files 20-23, 26-29 (summaries, ACH, HV).
--
-- Run the whole file in Snowsight as PROGRAMMER_DEV_ROLE (it owns all of them).

USE ROLE PROGRAMMER_DEV_ROLE;

-- 1) The daily rebuild: task first (a task graph can only change while its root is suspended)
ALTER TASK V2RETAIL.SILVER.TREND_L30_LOAD SUSPEND;
DROP TASK IF EXISTS V2RETAIL.SILVER.TREND_L30_PSF_VIEWS;
ALTER TASK V2RETAIL.SILVER.TREND_L30_LOAD RESUME;

DROP PROCEDURE IF EXISTS V2RETAIL.SILVER.USP_REBUILD_PSF_VIEWS(VARCHAR);

-- 2) Store chain (top of the chain first)
DROP VIEW IF EXISTS V2RETAIL.SILVER.V_ARTICLE_HV;
DROP VIEW IF EXISTS V2RETAIL.SILVER.V_ARTICLE_MAJCAT_PSF_ACH;
DROP VIEW IF EXISTS V2RETAIL.SILVER.V_ARTICLE_MAJCAT_PSF;
DROP VIEW IF EXISTS V2RETAIL.SILVER.V_TREND_30_DAYS_GRID_PSF_SUMMARY;
DROP VIEW IF EXISTS V2RETAIL.SILVER.V_MAJ_CAT_TREND_PSF_SUMMARY;
DROP VIEW IF EXISTS V2RETAIL.SILVER.V_TREND_30_DAYS_GRID_PSF;
DROP VIEW IF EXISTS V2RETAIL.SILVER.V_MAJ_CAT_TREND_PSF;
DROP VIEW IF EXISTS V2RETAIL.SILVER.V_TREND_30_DAYS_GRID;
DROP VIEW IF EXISTS V2RETAIL.SILVER.V_MAJ_CAT_TREND;

-- 3) MRDC chain
DROP VIEW IF EXISTS V2RETAIL.SILVER.V_MRDC_ARTICLE_HV;
DROP VIEW IF EXISTS V2RETAIL.SILVER.V_MRDC_ARTICLE_MAJCAT_PSF_ACH;
DROP VIEW IF EXISTS V2RETAIL.SILVER.V_MRDC_ARTICLE_MAJCAT_PSF;
DROP VIEW IF EXISTS V2RETAIL.SILVER.V_MRDC_TREND_30_DAYS_GRID_PSF_SUMMARY;
DROP VIEW IF EXISTS V2RETAIL.SILVER.V_MRDC_TREND_MAJ_CAT_30_DAYS_GRID_PSF_SUMMARY;
DROP VIEW IF EXISTS V2RETAIL.SILVER.V_MRDC_TREND_30_DAYS_GRID_PSF;
DROP VIEW IF EXISTS V2RETAIL.SILVER.V_MRDC_TREND_MAJ_CAT_30_DAYS_GRID_PSF;
DROP VIEW IF EXISTS V2RETAIL.SILVER.V_MRDC_TREND_30_DAYS_GRID;
DROP VIEW IF EXISTS V2RETAIL.SILVER.V_MRDC_TREND_MAJ_CAT_30_DAYS_GRID;

-- 4) Check: 0 views left, task chain = LOAD -> PIVOT -> MAJ_CAT, GRID (all "started")
SELECT COUNT(*) AS old_views_left
FROM V2RETAIL.INFORMATION_SCHEMA.VIEWS
WHERE TABLE_SCHEMA = 'SILVER'
  AND TABLE_NAME IN ('V_TREND_30_DAYS_GRID', 'V_MAJ_CAT_TREND', 'V_TREND_30_DAYS_GRID_PSF', 'V_MAJ_CAT_TREND_PSF',
                     'V_TREND_30_DAYS_GRID_PSF_SUMMARY', 'V_MAJ_CAT_TREND_PSF_SUMMARY', 'V_ARTICLE_MAJCAT_PSF',
                     'V_ARTICLE_MAJCAT_PSF_ACH', 'V_ARTICLE_HV', 'V_MRDC_TREND_30_DAYS_GRID', 'V_MRDC_TREND_MAJ_CAT_30_DAYS_GRID',
                     'V_MRDC_TREND_30_DAYS_GRID_PSF', 'V_MRDC_TREND_MAJ_CAT_30_DAYS_GRID_PSF', 'V_MRDC_TREND_30_DAYS_GRID_PSF_SUMMARY',
                     'V_MRDC_TREND_MAJ_CAT_30_DAYS_GRID_PSF_SUMMARY', 'V_MRDC_ARTICLE_MAJCAT_PSF', 'V_MRDC_ARTICLE_MAJCAT_PSF_ACH',
                     'V_MRDC_ARTICLE_HV');

SELECT NAME, STATE, PREDECESSORS
FROM TABLE(V2RETAIL.INFORMATION_SCHEMA.TASK_DEPENDENTS(TASK_NAME => 'V2RETAIL.SILVER.TREND_L30_LOAD', RECURSIVE => TRUE));
