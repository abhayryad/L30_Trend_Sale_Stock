-- V_ARTICLE_MAJCAT_PSF: article (MATNR) x store PSF summary, with the store + MAJ-CAT PSF/STR averages
-- brought alongside, matched on STORE_CODE + MAJ-CAT.
--   All columns of V_TREND_30_DAYS_GRID_PSF_SUMMARY, then MAJCAT_<KPI>_<window> from
--   V_MAJ_CAT_TREND_PSF_SUMMARY for KPI = SALE_PSF, GP_PSF, STR and window = MTD, L7D, 30D, TD.
--   Articles with no matching store + MAJ-CAT row get 0.
-- Run 20_v_psf_summary.sql first.

CREATE OR REPLACE VIEW V2RETAIL.SILVER.V_ARTICLE_MAJCAT_PSF AS
SELECT A.*,
       COALESCE(M.SALE_PSF_MTD, 0) AS MAJCAT_SALE_PSF_MTD,
       COALESCE(M.SALE_PSF_L7D, 0) AS MAJCAT_SALE_PSF_L7D,
       COALESCE(M.SALE_PSF_30D, 0) AS MAJCAT_SALE_PSF_30D,
       COALESCE(M.SALE_PSF_TD, 0)  AS MAJCAT_SALE_PSF_TD,
       COALESCE(M.GP_PSF_MTD, 0)   AS MAJCAT_GP_PSF_MTD,
       COALESCE(M.GP_PSF_L7D, 0)   AS MAJCAT_GP_PSF_L7D,
       COALESCE(M.GP_PSF_30D, 0)   AS MAJCAT_GP_PSF_30D,
       COALESCE(M.GP_PSF_TD, 0)    AS MAJCAT_GP_PSF_TD,
       COALESCE(M.STR_MTD, 0)      AS MAJCAT_STR_MTD,
       COALESCE(M.STR_L7D, 0)      AS MAJCAT_STR_L7D,
       COALESCE(M.STR_30D, 0)      AS MAJCAT_STR_30D,
       COALESCE(M.STR_TD, 0)       AS MAJCAT_STR_TD
FROM V2RETAIL.SILVER.V_TREND_30_DAYS_GRID_PSF_SUMMARY A
LEFT JOIN V2RETAIL.SILVER.V_MAJ_CAT_TREND_PSF_SUMMARY M
       ON A.STORE_CODE = M.STORE_CODE
      AND A."MAJ-CAT"  = M."MAJ-CAT";
