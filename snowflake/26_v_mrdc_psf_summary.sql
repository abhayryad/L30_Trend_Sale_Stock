-- MRDC (all-stores) PSF summary views: the left-hand block of each MRDC PSF view, up to and including the STR averages.
-- No per-day columns. Their source views are rebuilt daily by USP_REBUILD_PSF_VIEWS (30_USP_REBUILD_PSF_VIEWS.sql).
--   dimensions, FINAL_DENSITY, APF, PPA,
--   SALE_PSF / GP_PSF / STR averages for MTD, L7D, 30D and TD (same order as the source views)

-- MATNR grain (from V_MRDC_TREND_30_DAYS_GRID_PSF)
CREATE OR REPLACE VIEW V2RETAIL.SILVER.V_MRDC_TREND_30_DAYS_GRID_PSF_SUMMARY AS
SELECT SEG, DIV, "SUB-DIV", MATNR, "MAJ-CAT", "MC-CD", SIZE, COLOR,
       M_FAB_MAIN_MVGR_1, M_FAB_MAIN_MVGR_2, M_FIT, "M-VND-CD", MRP, REG_SEG,
       FINAL_DENSITY, APF, PPA,
       SALE_PSF_MTD, SALE_PSF_L7D, SALE_PSF_30D, SALE_PSF_TD,
       GP_PSF_MTD, GP_PSF_L7D, GP_PSF_30D, GP_PSF_TD,
       STR_MTD, STR_L7D, STR_30D, STR_TD
FROM V2RETAIL.SILVER.V_MRDC_TREND_30_DAYS_GRID_PSF;

-- MAJ-CAT grain (from V_MRDC_TREND_MAJ_CAT_30_DAYS_GRID_PSF)
CREATE OR REPLACE VIEW V2RETAIL.SILVER.V_MRDC_TREND_MAJ_CAT_30_DAYS_GRID_PSF_SUMMARY AS
SELECT SEG, DIV, "SUB-DIV", "MAJ-CAT",
       FINAL_DENSITY, APF, PPA,
       SALE_PSF_MTD, SALE_PSF_L7D, SALE_PSF_30D, SALE_PSF_TD,
       GP_PSF_MTD, GP_PSF_L7D, GP_PSF_30D, GP_PSF_TD,
       STR_MTD, STR_L7D, STR_30D, STR_TD
FROM V2RETAIL.SILVER.V_MRDC_TREND_MAJ_CAT_30_DAYS_GRID_PSF;
