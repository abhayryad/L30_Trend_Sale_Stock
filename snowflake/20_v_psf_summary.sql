-- PSF summary views: the left-hand block of each PSF view, up to and including the STR averages.
-- No per-day columns. Run 18_v_trend_30_days_grid_psf.sql and 19_v_maj_cat_trend_psf.sql first.
--   dimensions, FINAL_DENSITY, APF, PPA,
--   SALE_PSF / GP_PSF / STR averages for MTD, L7D, 30D and TD (same order as the source views)

-- MATNR grain (from V_TREND_30_DAYS_GRID_PSF)
CREATE OR REPLACE VIEW V2RETAIL.SILVER.V_TREND_30_DAYS_GRID_PSF_SUMMARY AS
SELECT SEG, DIV, "SUB-DIV", STORE_CODE, MATNR, "MAJ-CAT", "MC-CD", SIZE, COLOR,
       M_FAB_MAIN_MVGR_1, M_FAB_MAIN_MVGR_2, M_FIT, "M-VND-CD", MRP, REG_SEG,
       FINAL_DENSITY, APF, PPA,
       SALE_PSF_MTD, SALE_PSF_L7D, SALE_PSF_30D, SALE_PSF_TD,
       GP_PSF_MTD, GP_PSF_L7D, GP_PSF_30D, GP_PSF_TD,
       STR_MTD, STR_L7D, STR_30D, STR_TD
FROM V2RETAIL.SILVER.V_TREND_30_DAYS_GRID_PSF;

-- Store + MAJ-CAT grain (from V_MAJ_CAT_TREND_PSF)
CREATE OR REPLACE VIEW V2RETAIL.SILVER.V_MAJ_CAT_TREND_PSF_SUMMARY AS
SELECT SEG, DIV, "SUB-DIV", STORE_CODE, "MAJ-CAT",
       FINAL_DENSITY, APF, PPA,
       SALE_PSF_MTD, SALE_PSF_L7D, SALE_PSF_30D, SALE_PSF_TD,
       GP_PSF_MTD, GP_PSF_L7D, GP_PSF_30D, GP_PSF_TD,
       STR_MTD, STR_L7D, STR_30D, STR_TD
FROM V2RETAIL.SILVER.V_MAJ_CAT_TREND_PSF;
